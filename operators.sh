#!/usr/bin/bash
echo 'Validate if file or directory exists'
echo '[ -e /tmp/ ] ; echo $?'
echo 'Validate if file exists, but no directory'
echo '[ -f file ] ; echo $?'
echo 'Validate if file exists and is symlink'
echo '[ -h link-file ] ; echo $?'
echo 'Validates if file has read,write or execution permission'
echo '[ -r executor.sh ] ; echo $?'
echo '[ -w executor.sh ] ; echo $?'
echo '[ -x executor.sh ] ; echo $?'
echo 'Validates if my user is owner of file'
echo '[ -O file ] ; echo $?'
echo 'Validates if my group access to the file'
echo '[ -G file ] ; echo $?'
echo 'Verify if is character device' 
echo '[ -c /dev/tty0 ] ; echo $?'
echo 'Verify if is block device'
echo '[ -v /dev/sda ] ; echo $?'
echo 'Verify if file is not empty'
echo '[ -s file ] ; echo $?'
echo 'Verify if file is newer than the other'
echo '[ file -nt other-file ] ; echo $?'
echo 'Verify if file is older than the other'
echo '[ file -nt other-file ] ; echo $?'
echo 'Verify if two files point to the same inode'
echo '[ file -ef other-file ] ; echo $?'

